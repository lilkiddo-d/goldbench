#!/usr/bin/env node
// Exports Foundry artifact ABIs into a typed TS module (`as const` for viem inference).
// Usage: pnpm --filter app abis   (requires `forge build` output in ../contracts/out)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, "../../contracts/out");
const target = resolve(here, "../src/abi/generated.ts");

const contracts = [
  "RotationVault",
  "SignalEngine",
  "PriceHistory",
  "ProjectTokenHooks",
  "FeeCollector",
  "MarketClock",
  "VaultFactory",
  "ChainlinkOracleAdapter",
];

const camel = (name) => name.charAt(0).toLowerCase() + name.slice(1) + "Abi";

let src = "// AUTO-GENERATED by scripts/export-abis.mjs from contracts/out — do not edit by hand.\n";
src += "// Re-run `pnpm --filter app abis` after `forge build` to refresh.\n\n";

for (const name of contracts) {
  const file = join(outDir, `${name}.sol`, `${name}.json`);
  if (!existsSync(file)) {
    console.error(`missing artifact: ${file} (run forge build first)`);
    process.exit(1);
  }
  const { abi } = JSON.parse(readFileSync(file, "utf8"));
  if (!Array.isArray(abi)) {
    console.error(`no abi in ${file}`);
    process.exit(1);
  }
  src += `export const ${camel(name)} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
  console.log(`  ${name}: ${abi.length} entries`);
}

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, src);
console.log(`wrote ${target}`);
